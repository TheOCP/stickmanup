// A row of sharp teeth along a line.
function teeth(c, x0, y0, x1, y1, n, h, down = 1) {
  for (let i = 0; i < n; i++) {
    const a = i / n, b = (i + 1) / n, xa = x0 + (x1 - x0) * a, ya = y0 + (y1 - y0) * a, xb = x0 + (x1 - x0) * b, yb = y0 + (y1 - y0) * b;
    c.p(`M${xa} ${ya}L${(xa + xb) / 2} ${(ya + yb) / 2 + h * down}L${xb} ${yb}Z`, '#fffdf2', { lw: 0.8 });
  }
}
// A fierce slit eye.
function slit(c, x, y, w, h, tilt, iris = ['#fff08a', '#ffb01a']) {
  c.e(x, y, w, h, tilt, iris, { y: [y - h, y + h], lw: 1.4 });
  c.e(x, y, w * 0.2, h * 0.9, tilt, '#10060a', { ink: false });
  c.hi(x - w * 0.35, y - h * 0.35, w * 0.2, h * 0.25);
}
