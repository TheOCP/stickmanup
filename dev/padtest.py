"""Plays through every menu with a simulated controller: nothing may need a finger. Prints PASS or FAIL per check.
Usage: python dev/padtest.py OUTDIR"""
import functools, http.server, os, sys, threading
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT = Path(__file__).resolve().parent.parent / "assets"
out = Path(sys.argv[1] if len(sys.argv) > 1 else "dev/out/pad"); out.mkdir(parents=True, exist_ok=True)
class Q(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a): pass
srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), functools.partial(Q, directory=str(ROOT)))
threading.Thread(target=srv.serve_forever, daemon=True).start()
A, B, X, Y, LB, RB, SELECT, START, UP, DOWN, LEFT, RIGHT = 0, 1, 2, 3, 4, 5, 8, 9, 12, 13, 14, 15
STUB = """
window.__pad = { id: 'Test Controller', mapping: 'standard', connected: true, axes: [0, 0, 0, 0], buttons: Array.from({ length: 17 }, () => ({ pressed: false, value: 0 })) };
Object.defineProperty(navigator, 'getGamepads', { value: () => [window.__pad] });
localStorage.setItem('smu.settings', JSON.stringify({ quality: 'high', map: 5, name: 'Ana', tips: false, cap: 60 }));
localStorage.setItem('smu.profile', JSON.stringify({ coins: 5000, earned: 5000, own: [], eq: null, relics: [], ach: [], runs: {}, totals: {} }));
"""
fails = []
def check(name, ok, info=""):
    print(("PASS " if ok else "FAIL ") + name + (f"  [{info}]" if info and not ok else ""), flush=True)
    if not ok: fails.append(name)
with sync_playwright() as p:
    b = p.chromium.launch(args=["--use-angle=vulkan", "--enable-features=Vulkan", "--use-vulkan=native", "--disable-vulkan-surface", "--ignore-gpu-blocklist", "--disable-gpu-compositing"],
                          env={**os.environ, "VK_ICD_FILENAMES": "/usr/share/vulkan/icd.d/lvp_icd.json"})
    pg = b.new_page(viewport={"width": 915, "height": 412})
    errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.add_init_script(STUB)
    pg.goto(f"http://127.0.0.1:{srv.server_port}/index.html?native=rec")
    pg.wait_for_function("window.SMU && SMU.pool && SMU.pool.warm === 0", timeout=120000)
    def frames(n=4): pg.evaluate("n => new Promise((r) => { const f = () => (--n <= 0 ? r() : requestAnimationFrame(f)); requestAnimationFrame(f); })", n + 1)
    def press(i):
        pg.evaluate("i => { __pad.buttons[i].pressed = true; }", i); frames()
        pg.evaluate("i => { __pad.buttons[i].pressed = false; }", i); frames()
    def axes(*a): pg.evaluate("a => { __pad.axes = a; }", list(a)); frames()
    # What the highlight is on, as "data-a" or the element's id or text.
    ON = """() => { const e = document.querySelector('.pf'); if (!e) return null; const c = e.matches('label') ? e.querySelector('input') : e, d = c.dataset;
      return { a: d.a || '', k: d.k || d.c || '', v: d.v || '', id: d.id || '', t: d.t || '', m: d.m || '', d: d.d || '', e: d.e || '', ch: d.ch || '', tag: c.tagName, type: c.type || '', text: e.textContent.trim().slice(0, 30), inview: (() => { const r = e.getBoundingClientRect(); return r.top >= -1 && r.bottom <= innerHeight + 1; })() }; }"""
    def on(): return pg.evaluate(ON)
    def scr(): return pg.evaluate("SMU.screen")
    def seek(test, keys=(DOWN,), limit=60):
        """Moves in the given directions until the highlight satisfies test."""
        for _ in range(limit):
            o = on()
            if o and test(o): return True
            for k in keys: press(k)
        o = on()
        return bool(o and test(o))
    def findA(a, **kw): return seek(lambda o: o["a"] == a, **kw)

    # ---- title
    check("no highlight before the controller is used", on() is None)
    press(DOWN)
    o = on()
    check("first press only wakes the highlight, on the main button", bool(o) and o["a"] in ("solo", "cont"), str(o))
    check("the hint bar shows", pg.evaluate("document.querySelector('#padHint').classList.contains('on')"))
    press(B); frames()
    check("B on the title does nothing", scr() == "title")
    # ---- settings
    check("reach Settings from the title", findA("settings"))
    press(A); frames()
    check("A opens Settings", scr() == "settings", scr())
    check("Settings has one column with a controller", pg.evaluate("getComputedStyle(document.querySelector('.set')).gridTemplateColumns.trim().split(' ').length") == 1)
    pg.screenshot(path=str(out / "settings.png"))
    check("reach the left stick dead zone", seek(lambda o: o["k"] == "deadL"))
    check("the highlight stays in view when scrolling", on()["inview"])
    v0 = pg.evaluate("SMU.input.deadL")
    press(RIGHT); press(RIGHT)
    v1 = pg.evaluate("SMU.input.deadL")
    check("right raises the dead zone", abs(v1 - v0 - 0.04) < 1e-6, f"{v0} to {v1}")
    check("the value shows", pg.evaluate("document.querySelector('[data-v=deadL]').textContent") == f"{round(v1 * 100)}%")
    # Up to 34%, then a stick drifting at 30% must do nothing, in the menu or in the climb.
    pg.evaluate("__pad.buttons[15].pressed = true")
    pg.wait_for_function("SMU.input.deadL >= 0.34", timeout=15000)
    pg.evaluate("__pad.buttons[15].pressed = false"); frames()
    held = pg.evaluate("SMU.input.deadL")
    check("holding right keeps going", held >= 0.34, str(held))
    while pg.evaluate("SMU.input.deadL") > 0.341: press(LEFT)
    before = on()
    axes(0.3, 0.1, 0, 0)
    pg.screenshot(path=str(out / "drift.png"))
    check("stick test: dot inside its ring shows grey", pg.evaluate("document.querySelector('#psL').classList.contains('in')"))
    check("stick test: names the controller", pg.evaluate("document.querySelector('#psN').textContent") == "Test Controller")
    frames(20)
    check("a drifting stick does not move the highlight", on() == before)
    axes(0, 0, 0, 0)
    # A checkbox and a row of choices
    check("reach a checkbox", seek(lambda o: o["type"] == "checkbox"))
    ck = on()["k"]; c0 = pg.evaluate("k => document.querySelector(`[data-c=${k}]`).checked", ck)
    press(A)
    check("A flips a checkbox", pg.evaluate("k => document.querySelector(`[data-c=${k}]`).checked", ck) != c0)
    press(A)
    # The name box opens the letter board
    check("reach the name box", seek(lambda o: o["tag"] == "INPUT" and o["type"] == "text", keys=(DOWN,)) or seek(lambda o: o["tag"] == "INPUT" and o["type"] == "text", keys=(UP,)))
    press(A)
    check("A on a text box opens the letter board", pg.evaluate("!!document.querySelector('#padKeys')"))
    pg.screenshot(path=str(out / "keys.png"))
    press(X); press(X); press(X)
    check("X deletes", pg.evaluate("document.querySelector('#nm').value") == "")
    check("reach a letter", seek(lambda o: o["ch"] != "", keys=(RIGHT, UP)))
    ch = on()["ch"]; press(A); press(LEFT); press(A)
    nm = pg.evaluate("document.querySelector('#nm').value")
    check("A types (a capital first, then small)", len(nm) == 2 and nm[0] == ch and nm[1].islower() or nm[1].isdigit(), nm)
    press(B)
    check("B closes the letter board", not pg.evaluate("!!document.querySelector('#padKeys')"))
    check("the highlight is back on the box", on() and on()["tag"] == "INPUT", str(on()))
    frames(10)
    press(B); frames()
    check("B leaves Settings", scr() == "title", scr())
    o = on()
    check("the title remembers where you were", bool(o) and o["a"] == "settings", str(o))
    # ---- how to play: nothing to press but lots to read
    check("reach How to play", seek(lambda o: o["a"] == "how", keys=(RIGHT,), limit=3))
    press(A); frames()
    check("How to play opens", scr() == "how", scr())
    s0 = pg.evaluate("document.querySelector('.panel').scrollTop")
    press(DOWN); press(DOWN)
    check("down scrolls the text when there is nothing else to go to", pg.evaluate("document.querySelector('.panel').scrollTop") > s0)
    press(B); frames()
    # ---- shop: character selection
    check("reach the shop", seek(lambda o: o["a"] == "shop", keys=(UP, LEFT), limit=6))
    press(A); frames(8)
    check("A opens the shop", scr() == "shop", scr())
    o = on()
    check("the highlight starts on the first item", bool(o) and o["a"] == "pick", str(o))
    tab0 = pg.evaluate("document.querySelector('.tabs .on').dataset.t")
    press(RB); frames(6)
    tab1 = pg.evaluate("document.querySelector('.tabs .on').dataset.t")
    check("RB switches tab", tab1 != tab0, tab1)
    o = on()
    check("the highlight lands in the new tab", bool(o) and o["a"] == "pick", str(o))
    press(LB); frames(6)
    check("LB switches back", pg.evaluate("document.querySelector('.tabs .on').dataset.t") == tab0)
    # An owned item: try on, then wear
    check("reach a thing you don't wear yet", seek(lambda o: o["a"] == "pick" and "Wearing" not in o["text"] and "Owned" in o["text"], keys=(RIGHT,), limit=12) or seek(lambda o: o["a"] == "pick" and "Owned" in o["text"] and "Wearing" not in o["text"], keys=(DOWN,), limit=20))
    it = on()["id"]; press(A); frames(4)
    o = on()
    check("A tries it on and the highlight stays", bool(o) and o["id"] == it, str(o))
    pg.screenshot(path=str(out / "shop.png"))
    press(A); frames(4)
    check("A again wears it", pg.evaluate("JSON.stringify(JSON.parse(localStorage.getItem('smu.profile')||'{}'))") is not None and "Wearing" in on()["text"], str(on()))
    # A priced item: A only moves to the buy button
    check("reach something with a price", seek(lambda o: o["a"] == "pick" and "Owned" not in o["text"] and "Wearing" not in o["text"] and "Locked" not in o["text"], keys=(DOWN,), limit=30) or seek(lambda o: o["a"] == "pick" and "Owned" not in o["text"] and "Wearing" not in o["text"] and "Locked" not in o["text"], keys=(RIGHT,), limit=6))
    coins0 = pg.evaluate("document.querySelector('.wallet b').textContent")
    press(A); frames(4); press(A); frames(4)
    o = on()
    check("A twice does not spend coins, it goes to the buy button", bool(o) and o["a"] == "buy" and pg.evaluate("document.querySelector('.wallet b').textContent") == coins0, str(o))
    press(A); frames(6)
    check("A on Buy buys it", pg.evaluate("document.querySelector('.wallet b').textContent") != coins0)
    y0 = pg.evaluate("SMU.preview.yaw"); axes(0, 0, 0.9, 0); frames(8); axes(0, 0, 0, 0)
    check("the right stick turns the climber", pg.evaluate("SMU.preview.yaw") - y0 > 0.2)
    press(B); frames(4)
    check("B leaves the shop", scr() == "title" and not pg.evaluate("SMU.preview"), scr())
    # ---- records: switching maps
    check("reach Records", seek(lambda o: o["a"] == "records", keys=(RIGHT,), limit=3))
    press(A); frames(4)
    m0 = pg.evaluate("document.querySelector('.mapchips .on').dataset.m"); press(RB); frames(4)
    check("RB switches the map in Records", pg.evaluate("document.querySelector('.mapchips .on').dataset.m") != m0)
    press(B); frames(4)
    # ---- join: typing a code
    check("reach Join", seek(lambda o: o["a"] == "join", keys=(UP,), limit=6))
    press(A); frames(4)
    check("Join opens", scr() == "join", scr())
    check("the highlight starts in the code box", on() and on()["tag"] == "INPUT", str(on()))
    press(A)
    check("reach a letter on the board", seek(lambda o: o["ch"] != "", keys=(UP, RIGHT), limit=6))
    press(A); press(RIGHT); press(A)
    check("the board fills the code box in capitals", len(pg.evaluate("document.querySelector('#code').value")) == 2 and pg.evaluate("document.querySelector('#code').value").isupper() or pg.evaluate("document.querySelector('#code').value").isdigit(), pg.evaluate("document.querySelector('#code').value"))
    check("reach Done", seek(lambda o: o["e"] == "done", keys=(DOWN, RIGHT), limit=10))
    press(A); frames(2)
    check("Done closes and moves on to the Join button", pg.evaluate("!document.querySelector('#padKeys')") and on() and on()["tag"] == "BUTTON", str(on()))
    tb0 = pg.evaluate("document.querySelector('.tabs .on').dataset.t"); press(RB); frames(4)
    check("RB switches the join tabs", pg.evaluate("document.querySelector('.tabs .on').dataset.t") != tb0)
    press(B); frames(4)
    check("B leaves Join", scr() == "title", scr())
    # ---- host: all the way into the lobby screens
    check("reach Host", seek(lambda o: o["a"] == "host", keys=(UP,), limit=4))
    press(A); frames(4)
    check("Host opens", scr() == "host", scr())
    press(B); frames(4)
    # ---- solo: pick a map and difficulty, into the climb
    check("reach Solo", seek(lambda o: o["a"] == "solo", keys=(UP,), limit=4))
    press(A); frames(4)
    check("Solo opens", scr() == "solo", scr())
    pg.screenshot(path=str(out / "solo.png"))
    check("reach the difficulty cards", seek(lambda o: o["a"] == "pick", keys=(DOWN,), limit=14), str(on()))
    check("reach Normal", seek(lambda o: o["d"] == "1", keys=(LEFT,), limit=3) or seek(lambda o: o["d"] == "1", keys=(RIGHT,), limit=3), str(on()))
    pg.screenshot(path=str(out / "diff.png"))
    pg.evaluate("__pad.buttons[0].pressed = true"); frames(30)
    check("the climb starts", scr() == "game" and pg.evaluate("!!SMU.game"), scr())
    check("no highlight during play", on() is None)
    check("no hint bar during play", not pg.evaluate("document.querySelector('#padHint').classList.contains('on')"))
    vy = pg.evaluate("SMU.game.me.vy")
    check("the A that started the climb does not jump", abs(vy) < 3 and pg.evaluate("SMU.game.me.grounded !== false"), str(vy))
    pg.evaluate("__pad.buttons[0].pressed = false"); frames()
    # ---- drift against the dead zone during play
    frames(20)
    x0 = pg.evaluate("[SMU.game.me.x, SMU.game.me.z, SMU.game.cam.yaw]")
    axes(0.3, 0.1, 0.3, 0.1); frames(30)
    x1 = pg.evaluate("[SMU.game.me.x, SMU.game.me.z, SMU.game.cam.yaw]")
    check("left stick inside the dead zone does not walk", abs(x1[0] - x0[0]) + abs(x1[1] - x0[1]) < 0.02, f"{x0} to {x1}")
    pg.evaluate("SMU.input.deadR = 0.1"); frames(10)
    x2 = pg.evaluate("SMU.game.cam.yaw")
    check("right stick outside its dead zone turns the camera", abs(x2 - x1[2]) > 0.002, f"{x1[2]} to {x2}")
    axes(0, 0, 0, 0); pg.evaluate("SMU.input.deadR = 0.16")
    axes(0.95, 0, 0, 0); frames(30)
    x3 = pg.evaluate("[SMU.game.me.x, SMU.game.me.z]")
    check("a full push walks", abs(x3[0] - x1[0]) + abs(x3[1] - x1[1]) > 0.3, f"{x1} to {x3}")
    axes(0, 0, 0, 0)
    # ---- pause and checkpoints
    press(START); frames()
    check("Start pauses", scr() == "pause", scr())
    o = on(); check("the highlight is on Resume", bool(o) and o["a"] == "back", str(o))
    press(B); frames()
    check("B resumes", scr() == "game", scr())
    press(SELECT); frames()
    o = on(); check("Select opens the pause menu on Back to checkpoint", scr() == "pause" and bool(o) and o["a"] == "respawn", str(o))
    pg.screenshot(path=str(out / "pause.png"))
    pg.evaluate("() => { window.__sent = []; const g = SMU.game, f = g.s.toHost; g.s.toHost = function (m) { __sent.push(m.k); return f.call(this, m); }; }")
    press(A); frames(6)
    check("A goes back to the checkpoint", scr() == "game" and "restart" in pg.evaluate("__sent"), str(pg.evaluate("__sent")))
    press(START); frames()
    check("reach Settings from pause", findA("settings"))
    press(A); frames()
    check("Settings opens from pause", scr() == "settings", scr())
    press(B); frames()
    check("B returns to the pause menu", scr() == "pause", scr())
    press(START); frames()
    check("Start resumes", scr() == "game", scr())
    press(START); frames()
    check("reach Save and quit", findA("quit"))
    press(A); frames(10)
    check("Save and quit reaches the title", scr() == "title", scr())
    # ---- touch takes over
    pg.mouse.click(5, 5); frames()
    check("touching the screen hides the highlight", on() is None and not pg.evaluate("document.body.classList.contains('pad')"))
    check("no script errors", not errs, str(errs[:3]))
    b.close()
print("ALL PASSED" if not fails else f"{len(fails)} FAILED: " + "; ".join(fails))
sys.exit(1 if fails else 0)
