package io.stickmanup.gl;

import java.nio.Buffer;

/** The OpenGL ES 3.0 calls the renderer uses. Android implements it with GLES30, desktop tests with JOGL. */
public interface GLApi {
    /** A marker in the command stream, to wait for the GPU to reach it (0 if it could not be made). */
    long fenceSync();
    void clientWaitSync(long sync, long nanos);
    void deleteSync(long sync);
    /** Tells the driver the current framebuffer's depth contents are no longer needed. */
    void invalidateDepth();
    int createShader(int type);
    void shaderSource(int s, String src);
    void compileShader(int s);
    int getShaderi(int s, int pname);
    String getShaderInfoLog(int s);
    int createProgram();
    void attachShader(int p, int s);
    void bindAttribLocation(int p, int index, String name);
    void linkProgram(int p);
    int getProgrami(int p, int pname);
    String getProgramInfoLog(int p);
    void useProgram(int p);
    int getUniformLocation(int p, String name);
    int getAttribLocation(int p, String name);
    void uniform1i(int l, int v);
    void uniform1f(int l, float v);
    void uniform2f(int l, float x, float y);
    void uniform3f(int l, float x, float y, float z);
    void uniform4f(int l, float x, float y, float z, float w);
    void uniformMatrix3fv(int l, float[] m);
    void uniformMatrix4fv(int l, float[] m);
    int genBuffer();
    void bindBuffer(int target, int b);
    void bufferData(int target, int bytes, Buffer data, int usage);
    void bufferSubData(int target, int offset, int bytes, Buffer data);
    int genVertexArray();
    void bindVertexArray(int v);
    void enableVertexAttribArray(int i);
    void disableVertexAttribArray(int i);
    void vertexAttribPointer(int i, int size, int type, boolean norm, int stride, int offset);
    void vertexAttribDivisor(int i, int d);
    void vertexAttrib4f(int i, float x, float y, float z, float w);
    void drawArrays(int mode, int first, int count);
    void drawElements(int mode, int count, int type, int offset);
    void drawArraysInstanced(int mode, int first, int count, int n);
    void drawElementsInstanced(int mode, int count, int type, int offset, int n);
    void viewport(int x, int y, int w, int h);
    void clearColor(float r, float g, float b, float a);
    void clear(int mask);
    void enable(int cap);
    void disable(int cap);
    void blendFunc(int s, int d);
    void depthMask(boolean on);
    void depthFunc(int f);
    void cullFace(int mode);
    int genTexture();
    void bindTexture(int target, int t);
    void activeTexture(int unit);
    void texParameteri(int target, int p, int v);
    void texImage2D(int target, int level, int ifmt, int w, int h, int fmt, int type, Buffer data);
    void generateMipmap(int target);
    int genFramebuffer();
    void bindFramebuffer(int target, int f);
    void framebufferTexture2D(int target, int att, int texTarget, int tex, int level);
    int genRenderbuffer();
    void bindRenderbuffer(int target, int r);
    void renderbufferStorage(int target, int fmt, int w, int h);
    void framebufferRenderbuffer(int target, int att, int rbTarget, int r);
    int checkFramebufferStatus(int target);
    void deleteTexture(int t);
    void deleteBuffer(int b);
    void deleteVertexArray(int v);
    void deleteFramebuffer(int f);
    void deleteRenderbuffer(int r);
    int getError();
    String getString(int name);
    void readPixels(int x, int y, int w, int h, int fmt, int type, Buffer buf);
}
